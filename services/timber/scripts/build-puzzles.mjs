// Precomputes boards into puzzles.js: a list of daily boards and a practice pool. A qualifying board takes seconds to
// find, so it can't happen on page load. Work is split across child processes.
//
//   node scripts/build-puzzles.mjs extend [ahead=365] [workers=4]
//     Keeps every existing day unchanged and appends new ones until `ahead` days past today (UTC). This is what the
//     scheduled workflow runs. Existing days are never regenerated, so a generator change can't alter a past board.
//
//   node scripts/build-puzzles.mjs rebuild [ahead=365] [workers=4] [pool=120]
//     Regenerates everything from EPOCH. Use only before launch or after a rules change.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fork } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const OUT = new URL('../puzzles.js', import.meta.url);
const EPOCH = '2026-10-30';
const DAY = 864e5;
const isoDay = ms => new Date(ms).toISOString().slice(0, 10);

if (process.argv[2] === '--worker') {
  const { generate, T } = await import('./generator.mjs');
  process.on('message', job => {
    if (job === 'done') process.exit(0);
    process.send({ ...job, rec: T.encode(generate(job.seed)) });
  });
  process.send({ ready: true });
} else {
  const [mode = 'extend', ahead = 365, workers = 4, pool = 120] = process.argv.slice(2).map((x, i) => i ? Number(x) : x);
  if (!['extend', 'rebuild'].includes(mode)) throw new Error(`unknown mode ${mode}`);
  let old = { epoch: EPOCH, daily: [], practice: [] };
  if (mode === 'extend' && existsSync(OUT)) {
    const ctx = {};
    vm.createContext(ctx);
    vm.runInContext(readFileSync(OUT, 'utf8') + '\nthis.P = PUZZLES;', ctx);
    old = ctx.P;
  }
  const out = { epoch: EPOCH, daily: old.daily.slice(), practice: mode === 'rebuild' ? [] : old.practice };
  const days = Math.round((Date.parse(isoDay(Date.now())) + ahead * DAY - Date.parse(EPOCH)) / DAY) + 1;
  const jobs = [];
  for (let i = out.daily.length; i < days; i++) jobs.push({ list: 'daily', i, seed: 'timber-daily-' + isoDay(Date.parse(EPOCH) + i * DAY) });
  for (let i = out.practice.length; i < pool; i++) jobs.push({ list: 'practice', i, seed: 'timber-practice-' + i });
  console.log(`${mode}: ${jobs.length} boards to find, ${workers} workers`);
  const t0 = Date.now();
  let running = 0, done = 0;
  const finish = () => {
    writeFileSync(OUT, `// Generated by scripts/build-puzzles.mjs. Each board: [x, y, height and sage digits per block, flag, flag, par].
// daily[i] is the board for epoch + i days.
const PUZZLES = ${JSON.stringify(out)};\n`);
    console.log(`daily ${out.daily.length} from ${out.epoch}, practice ${out.practice.length}, ${Math.round((Date.now() - t0) / 1000)} s`);
  };
  if (!jobs.length) finish();
  for (let w = 0; w < workers && jobs.length; w++) {
    running++;
    const child = fork(fileURLToPath(import.meta.url), ['--worker']);
    child.on('message', m => {
      if (!m.ready) { out[m.list][m.i] = m.rec; if (++done % 50 === 0) console.log(`${done} boards, ${Math.round((Date.now() - t0) / 1000)} s`); }
      const job = jobs.shift();
      child.send(job || 'done');
    });
    child.on('exit', code => {
      if (code) throw new Error(`worker exited with ${code}`);
      if (--running === 0) finish();
    });
  }
}
